#!/usr/bin/env python
"""Regenerate the source-influence results from raw prediction files: runs analyze.py per task and calibration,
native_repeat.py, map_fidelity.py, contrast.py and wrongq.py, then writes TABLES.md next to the runs and
results/summary/source_influence.json."""
import os, sys

sys.path.insert(0, os.path.join(os.path.dirname(os.path.abspath(__file__)), "..", "..", "baton"))
from paths import RAW, SUMMARY  # noqa: E402
import json, os, subprocess, sys

HERE = os.path.dirname(os.path.abspath(__file__))
PY = sys.executable
BASE = os.path.join(RAW, "source_influence")
RUNS = os.path.join(BASE, "confirm")
OUT = os.path.join(BASE, "tables")


def run(args):
    r = subprocess.run([PY] + args, capture_output=True, text=True, cwd=HERE)
    if r.returncode:
        print(r.stdout[-2000:], r.stderr[-4000:]); raise SystemExit(f"failed: {args}")
    return r.stdout


def main():
    os.makedirs(OUT, exist_ok=True)
    blocks = [("mmlu", "chat", "MMLU-base, chat-mixed maps (primary)"), ("gsm8k", "chat", "GSM8K, chat-mixed maps (primary)"),
              ("mmlu_chat", "chat", "MMLU-chat protocol, chat-mixed maps (robustness)"), ("mmlu", "web", "MMLU-base, web-calibrated maps (sensitivity)")]
    summary, md = {}, ["# Source-influence study: generated tables", "",
                       "Generated by `build_results.py` from the raw prediction files. Do not edit by hand.", ""]
    fid = json.loads(run([os.path.join(HERE, "map_fidelity.py"), os.path.join(OUT, "map_fidelity.json")]))
    md += ["## Map fidelity: FineWeb short prefix, % of the prefix benefit retained", "",
           "| direction | attention only | DeltaNet only | full handoff | full handoff + 64 native tokens | full-handoff KL | full-handoff top-1 |",
           "|---|---|---|---|---|---|---|"]
    for d, v in fid.items():
        md.append(f"| {d} | {v['attn_mapped']} | {v['delta_best']} | {v['combined_best']} | {v['combined_best_tail64']} | {v['combined_kl']} | {v['combined_top1']} |")
    md.append("")
    summary["map_fidelity"] = fid
    for task, calib, title in blocks:
        if not any(f.startswith(f"{task}__{calib}__") for f in os.listdir(RUNS)):
            md += [f"## {title}", "", "Not run or no output yet.", ""]
            continue
        sj, sm = os.path.join(OUT, f"summary_{task}_{calib}.json"), os.path.join(OUT, f"tables_{task}_{calib}.md")
        run([os.path.join(HERE, "analyze.py"), "--runs", RUNS, "--task", task, "--calib", calib, "--out", sj, "--md", sm])
        summary[f"{task}/{calib}"] = json.load(open(sj))
        body = open(sm).read().split("\n", 1)[1]
        md += [f"## {title}", body]
    rep = json.loads(run([os.path.join(HERE, "native_repeat.py"), RUNS, os.path.join(OUT, "native_repeat.json")]))
    summary["native_repeat"] = rep
    md += ["## Native repeat across worker groups", "",
           "| task/model | groups | items | identical prediction or tokens | identical correctness | accuracy in each run |", "|---|---|---|---|---|---|"]
    for k, v in rep.items():
        same = v.get("same_pred", v.get("token_identical"))
        corr = v.get("same_correctness", v.get("same_pred"))
        md.append(f"| {k} | {' vs '.join(v['groups'])} | {v['n']} | {same} | {corr} | {', '.join(f'{a:.1f}' for a in v['acc_each'])} |")
    md.append("")
    # exploratory donor-strength contrast (post hoc)
    md += ["## Exploratory: donor-strength contrast (post hoc)", "",
           "Same receiver, same items: accuracy with the stronger donor minus accuracy with the weaker donor (points, 95% paired bootstrap CI).", "",
           "| task | receiver: stronger minus weaker donor | H-all | H-tail | H-ctx | C-swap |", "|---|---|---|---|---|---|"]
    summary["contrast"] = {}
    for task in ("mmlu", "mmlu_chat", "gsm8k"):
        c = json.loads(run([os.path.join(HERE, "contrast.py"), RUNS, task, os.path.join(OUT, f"contrast_{task}.json")]))
        summary["contrast"][task] = c
        recv = sorted({k.split(" | ")[0] for k in c})
        for rv in recv:
            cell = lambda cond: (lambda v: f"{v['diff']:+.1f} [{v['ci95'][0]:+.1f}, {v['ci95'][1]:+.1f}]" if v else "-")(c.get(f"{rv} | {cond}"))
            md.append(f"| {task} | {rv} | {cell('H-all')} | {cell('H-tail')} | {cell('H-ctx')} | {cell('C-swap')} |")
    md.append("")
    # verdict matrix
    md += ["## Verdict matrix", "", "| task | direction | H-all | H-tail | H-ctx |", "|---|---|---|---|---|"]
    NAMES = {"mmlu/chat": "MMLU-base", "mmlu_chat/chat": "MMLU-chat protocol", "gsm8k/chat": "GSM8K", "mmlu/web": "MMLU-base, web maps"}
    for key in ("mmlu/chat", "mmlu_chat/chat", "gsm8k/chat", "mmlu/web"):
        if key not in summary:
            continue
        for d, R in summary[key]["dirs"].items():
            md.append(f"| {NAMES[key]} | {d} | " + " | ".join(R["verdict"].get(c, {}).get("verdict", "-") for c in ("H-all", "H-tail", "H-ctx")) + " |")
    md.append("")
    # post hoc wrong-question donor control and treatment repeat
    wq_dir = os.path.join(BASE, "wrongq")
    if os.path.isdir(wq_dir) and any(f.endswith(".jsonl") for f in os.listdir(wq_dir)):
        wj, wm = os.path.join(OUT, "wrongq.json"), os.path.join(OUT, "wrongq.md")
        run([os.path.join(HERE, "wrongq.py"), wj, wm])
        summary["wrongq"] = json.load(open(wj))
        md += ["## Post hoc: wrong-question donor control", "",
               "The donor reads a different test item j with the same exemplar block; the mapped cache is installed and the "
               "receiver, continuing with item i's bridge token, is scored against item i's gold. From a separate run "
               "(the wrongq run) whose R-native and H-all also repeat the recorded confirmatory conditions.", "",
               open(wm).read()]
    open(os.path.join(OUT, "TABLES.md"), "w").write("\n".join(md) + "\n")
    json.dump(summary, open(os.path.join(SUMMARY, "source_influence.json"), "w"), indent=1, default=str)
    print("\n".join(md))


if __name__ == "__main__":
    main()
